"""Write the ``.env`` file for ``compose.yaml`` with strong random passwords (docs/M6_SPEC.md).

    python scripts/docker_env.py                 # writes <repo>/.env, refuses to overwrite
    python scripts/docker_env.py --force         # replace an existing .env
    python scripts/docker_env.py --out PATH      # write somewhere else

The passwords meet the SQL Server complexity rules (upper, lower, digit and symbol; 24
characters) and use only characters that are safe unquoted in a shell, inside single quotes in
a compose ``.env`` file and in a URL after percent-encoding: no ``$`` (compose interpolation),
quotes, backslash, ``#``, backtick or whitespace. Nothing secret is printed.
"""

from __future__ import annotations

import argparse
import os
import secrets
import string
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
LENGTH = 24
SYMBOLS = "-_.!@%^*+=:,"
CLASSES = (string.ascii_uppercase, string.ascii_lowercase, string.digits, SYMBOLS)
MIN_PER_CLASS = 2


def make_password(length: int = LENGTH) -> str:
    """Random password with at least ``MIN_PER_CLASS`` characters of every class."""
    if length < MIN_PER_CLASS * len(CLASSES):
        raise ValueError(f"length must be >= {MIN_PER_CLASS * len(CLASSES)}")
    rng = secrets.SystemRandom()
    chars = [secrets.choice(c) for c in CLASSES for _ in range(MIN_PER_CLASS)]
    alphabet = "".join(CLASSES)
    chars += [secrets.choice(alphabet) for _ in range(length - len(chars))]
    rng.shuffle(chars)
    password = "".join(chars)
    if not is_strong(password):  # cannot happen; never write a weak password silently
        raise RuntimeError("generated password failed the strength check")
    return password


def is_strong(password: str) -> bool:
    """SQL Server policy (>= 8 chars, 3 of 4 classes) plus our own stricter rules."""
    allowed = set("".join(CLASSES))
    return (
        len(password) >= 8
        and all(sum(ch in c for ch in password) >= MIN_PER_CLASS for c in CLASSES)
        and set(password) <= allowed
    )


def render(mssql: str, postgres: str) -> str:
    return (
        "# Generated by scripts/docker_env.py for compose.yaml. Do not commit (see .gitignore).\n"
        f"MSSQL_SA_PASSWORD='{mssql}'\n"
        f"POSTGRES_PASSWORD='{postgres}'\n"
        "# Host ports (published on 127.0.0.1 only)\n"
        "MSSQL_PORT=14330\n"
        "PG_PORT=54330\n"
    )


def write_env(path: Path, force: bool = False) -> None:
    """Write ``path``; ``FileExistsError`` if it exists and ``force`` is false."""
    content = render(make_password(), make_password())
    path.parent.mkdir(parents=True, exist_ok=True)
    flags = os.O_WRONLY | os.O_CREAT | (os.O_TRUNC if force else os.O_EXCL)
    # 0o600 on POSIX (ignored on Windows, where the user profile ACLs apply).
    fd = os.open(path, flags, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write .env for compose.yaml (random passwords).")
    parser.add_argument(
        "--out", type=Path, default=REPO_ROOT / ".env", help="output file (default: <repo>/.env)"
    )
    parser.add_argument("--force", action="store_true", help="overwrite an existing file")
    args = parser.parse_args(argv)
    out: Path = args.out
    try:
        write_env(out, force=args.force)
    except FileExistsError:
        print(
            f"error: {out} already exists; keep it, or re-run with --force to replace it "
            "(existing server volumes keep the OLD passwords: run `docker compose down -v` first)",
            file=sys.stderr,
        )
        return 1
    print(f"wrote {out} (MSSQL_SA_PASSWORD, POSTGRES_PASSWORD: {LENGTH} random characters each)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
